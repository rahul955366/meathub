def seed_data():
    import django
    import os
    os.environ.setdefault("DJANGO_SETTINGS_MODULE", "core.settings")
    django.setup()

    from django.contrib.auth.models import User
    from api.models import VillageSource, Butcher, MeatItem, UserProfile, PetFoodProduct, ButcherWasteCollection, Order, OrderItem

    print("Purging old data deeply...")
    OrderItem.objects.all().delete()
    Order.objects.all().delete()
    MeatItem.objects.all().delete()
    Butcher.objects.all().delete()
    VillageSource.objects.all().delete()
    PetFoodProduct.objects.all().delete()

    sources = []
    for vs_data in [
        {"name": "Sangareddy Farms", "loc": "Telangana"},
        {"name": "Nellore Fishery", "loc": "Andhra"},
        {"name": "Warangal Goat Center", "loc": "Telangana"}
    ]:
        sources.append(VillageSource.objects.create(name=vs_data["name"], location=vs_data["loc"]))

    for shop in SHOPS:
        user, _ = User.objects.get_or_create(username=shop["user"])
        if not user.has_usable_password():
            user.set_password("meathub2026")
            user.save()
        
        butcher = Butcher.objects.create(
            user=user,
            shop_name=shop["name"],
            address=shop["addr"],
            phone_number=shop["phone"],
            image_url=shop["img"],
            village_source=sources[shop["source_idx"]],
            latitude=shop["lat"],
            longitude=shop["lng"],
            opening_time=shop["open"],
            closing_time=shop["close"],
            status="APPROVED",
            is_available=True
        )

        for p in shop["products"]:
            MeatItem.objects.create(
                butcher=butcher,
                name=p["name"],
                category=p["cat"],
                price=p["price"],
                image_url=p["img"],
                status="AVAILABLE",
                quantity=100,
                is_gym_approved=p.get("is_gym_approved", False),
                is_pet_suitable=p.get("is_pet_suitable", False),
                product_type=p.get("product_type", "GENERAL")
            )

    # Pet Food Products
    PetFoodProduct.objects.create(
        name="Premium Mutton Organ Mix",
        description="Fresh organ meat for high energy pets.",
        price=180,
        image_url=IMAGES["mut_liver_1"],
        is_vet_approved=True
    )
    
    print("Seed Complete!")

