def seed_data():
    import django
    import os
    os.environ.setdefault("DJANGO_SETTINGS_MODULE", "core.settings")
    django.setup()

    from django.contrib.auth.models import User
    from api.models import (
        VillageSource, Butcher, MeatItem, UserProfile,
        PetFoodProduct, ButcherWasteCollection, Order, OrderItem
    )

    print("Purging old data...")
    OrderItem.objects.all().delete()
    Order.objects.all().delete()
    MeatItem.objects.all().delete()
    Butcher.objects.all().delete()
    VillageSource.objects.all().delete()
    PetFoodProduct.objects.all().delete()
    ButcherWasteCollection.objects.all().delete()

    # Village Sources
    sources = []
    for vs_data in [
        {"name": "Sangareddy Farms",     "loc": "Telangana"},
        {"name": "Nellore Fishery",      "loc": "Andhra Pradesh"},
        {"name": "Warangal Goat Center", "loc": "Telangana"}
    ]:
        sources.append(VillageSource.objects.create(
            name=vs_data["name"], location=vs_data["loc"]
        ))

    # Create Shops + Products
    for shop in SHOPS:
        user, _ = User.objects.get_or_create(username=shop["user"])
        if not user.has_usable_password():
            user.set_password("meathub2026")
            user.save()

        butcher = Butcher.objects.create(
            user=user,
            shop_name=shop["name"],
            address=shop["addr"],
            phone_number=shop["phone"],
            description=shop["desc"],
            image_url=shop["img"],
            village_source=sources[shop["source_idx"]],
            latitude=shop["lat"],
            longitude=shop["lng"],
            opening_time=shop["open"],
            closing_time=shop["close"],
            is_busy=shop.get("is_busy", False),
            active_orders=shop.get("active_orders", 0),
            is_official=shop.get("is_official", False),
            hygiene_score=5,
            status="APPROVED",
            is_available=True,
            daily_order_quota=50,
        )

        for p in shop["products"]:
            MeatItem.objects.create(
                butcher=butcher,
                name=p["name"],
                category=p["cat"],
                price=p["price"],
                image_url=p["img"],
                status="AVAILABLE",
                quantity=100,
                is_gym_approved=p.get("is_gym_approved", False),
                is_pet_suitable=p.get("is_pet_suitable", False),
                product_type=p.get("product_type", "GENERAL"),
                protein_g=p.get("protein_g", 0),
                fat_g=p.get("fat_g", 0),
                calories=p.get("calories", 0),
            )

        # Waste collections per butcher
        ButcherWasteCollection.objects.create(
            butcher=butcher,
            waste_type="Chicken Frames & Bones",
            quantity_kg=10,
            price_per_kg=20,
            is_available=True
        )
        ButcherWasteCollection.objects.create(
            butcher=butcher,
            waste_type="Mutton Organ Trimmings",
            quantity_kg=5,
            price_per_kg=30,
            is_available=True
        )

    # Pet Food Products
    PetFoodProduct.objects.create(
        name="Premium Mutton Organ Mix",
        description="Fresh organ meat blend for high energy dogs and cats.",
        price=180,
        image_url=IMAGES["pet_organ_1"],
        ingredients="Mutton liver, kidney, heart — freshly sourced daily",
        is_vet_approved=True
    )
    PetFoodProduct.objects.create(
        name="Raw Bone Chew Pack",
        description="Natural raw bones for dental health and enrichment.",
        price=120,
        image_url=IMAGES["pet_bones_1"],
        ingredients="Chicken frames, marrow bones — zero preservatives",
        is_vet_approved=True
    )

    print(f"Seed complete! {MeatItem.objects.count()} items across {Butcher.objects.count()} butchers.")


seed_data()